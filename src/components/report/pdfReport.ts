// ---------------------------------------------------------------------------
// Formatting helpers
// ---------------------------------------------------------------------------

function formatNumber(n: number): string {
  return n.toLocaleString('en-GB', { maximumFractionDigits: 0 })
}

function formatPercent(n: number): string {
  return `${n.toFixed(2)} %`
}

/** Parse a hex colour string to [r, g, b] tuple (0-255). */
function hexToRgb(hex: string): [number, number, number] {
  const h = hex.replace('#', '')
  return [parseInt(h.substring(0, 2), 16), parseInt(h.substring(2, 4), 16), parseInt(h.substring(4, 6), 16)]
}

// ---------------------------------------------------------------------------
// Shared PDF helpers
// ---------------------------------------------------------------------------

/** Set text colour from a hex string. */
function setTextColour(doc: jsPDF, hex: string): void {
  const [r, g, b] = hexToRgb(hex)
  doc.setTextColor(r, g, b)
}

/** Set draw colour from a hex string. */
function setDrawColour(doc: jsPDF, hex: string): void {
  const [r, g, b] = hexToRgb(hex)
  doc.setDrawColor(r, g, b)
}

/** Set fill colour from a hex string. */
function setFillColour(doc: jsPDF, hex: string): void {
  const [r, g, b] = hexToRgb(hex)
  doc.setFillColor(r, g, b)
}

/** Add footer text to every page of the document. */
function addFooters(doc: jsPDF, orientation: 'portrait' | 'landscape'): void {
  const totalPages = doc.getNumberOfPages()
  const footerY = orientation === 'portrait' ? 290 : 203
  const centreX = orientation === 'portrait' ? 105 : 148.5
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(8)
    setTextColour(doc, NEUTRAL_600)
    doc.text(FOOTER_TEXT, centreX, footerY, { align: 'center' })
  }
}

/** Draw a horizontal rule line across the page. */
function drawHr(doc: jsPDF, y: number, x1: number, x2: number): void {
  setDrawColour(doc, NEUTRAL_300)
  doc.setLineWidth(0.3)
  doc.line(x1, y, x2, y)
}

