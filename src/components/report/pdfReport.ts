/**
 * Render a Highcharts config to a PNG data URL by creating a temporary
 * off-screen chart, extracting its SVG, and converting to a canvas image.
 * Returns a data:image/png;base64 string ready for jsPDF addImage().
 */
async function renderChartToImage(
  options: Highcharts.Options,
  width: number,
  height: number,
): Promise<string> {
  const container = document.createElement('div')
  container.style.position = 'fixed'
  container.style.left = '-9999px'
  container.style.top = '-9999px'
  container.style.width = `${width}px`
  container.style.height = `${height}px`
  document.body.appendChild(container)

  const chart = Highcharts.chart(container, {
    ...options,
    chart: {
      ...(options.chart ?? {}),
      width,
      height,
      animation: false,
      // White background so the PDF image has a solid fill rather than transparent
      backgroundColor: WHITE,
    },
    // Disable interactions that are irrelevant for export
    tooltip: { ...((options.tooltip as Highcharts.TooltipOptions) ?? {}), enabled: false },
    plotOptions: {
      ...options.plotOptions,
      series: {
        ...(options.plotOptions?.series ?? {}),
        animation: false,
        enableMouseTracking: false,
      },
    },
  })

  // Extract SVG markup from the rendered chart's SVG element.
  // We read the outerHTML of the renderer's root <svg> rather than calling
  // chart.getSVG() which requires the exporting module.
  const svgElement = chart.renderer.box as SVGElement
  const svg = svgElement.outerHTML
  chart.destroy()
  document.body.removeChild(container)

  // Convert SVG markup to a PNG data URL via a temporary Image + canvas
  return new Promise<string>((resolve, reject) => {
    const img = new Image()
    const svgBlob = new Blob([svg], { type: 'image/svg+xml;charset=utf-8' })
    const url = URL.createObjectURL(svgBlob)
    img.onload = () => {
      // 2x resolution for retina-quality output in the PDF
      const scale = 2
      const canvas = document.createElement('canvas')
      canvas.width = width * scale
      canvas.height = height * scale
      const ctx = canvas.getContext('2d')
      if (!ctx) {
        URL.revokeObjectURL(url)
        reject(new Error('Could not get 2d canvas context'))
        return
      }
      ctx.scale(scale, scale)
      ctx.drawImage(img, 0, 0, width, height)
      URL.revokeObjectURL(url)
      resolve(canvas.toDataURL('image/png'))
    }
    img.onerror = () => {
      URL.revokeObjectURL(url)
      reject(new Error('Failed to load SVG into image for chart export'))
    }
    img.src = url
  })
}

