export interface ComparisonScenario {
  readonly name: string
  readonly portfolio: PortfolioState
  readonly results: {
    readonly hourlyScore: number
    readonly annualScore: number
    readonly totalExcessMWh: number
    readonly totalUnmatchedMWh: number
    readonly monthlyScores: readonly number[]
  }
}

export async function generateSingleScenarioPdf(
  name: string,
  state: PortfolioState,
  result: EngineResult,
): Promise<void> {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  const pageW = 210
  const margin = 20
  const contentW = pageW - 2 * margin

  // -------------------------------------------------------------------------
  // Page 1: Cover
  // -------------------------------------------------------------------------

  // Light teal header band
  setFillColour(doc, '#e6f5f3')
  doc.rect(0, 0, pageW, 60, 'F')

  // Title
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(24)
  setTextColour(doc, NEUTRAL_1000)
  doc.text(name, margin, 35)

  // Subtitle
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(11)
  setTextColour(doc, NEUTRAL_600)
  doc.text('Scenario Analysis Tool report', margin, 45)

  // KPI section
  let y = 75

  // Allocation method
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  setTextColour(doc, NEUTRAL_600)
  doc.text('Allocation method', margin, y)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(12)
  setTextColour(doc, NEUTRAL_1000)
  doc.text(granularityLabel(state.granularity), margin, y + 6)
  y += 20

  drawHr(doc, y, margin, margin + contentW)
  y += 10

  // Score cards (2 columns)
  const col1X = margin
  const col2X = margin + contentW / 2

  // Hourly score
  drawKpiCard(doc, col1X, y, 'Hourly matching score', formatPercent(result.portfolio.hourlyScore))
  // Annual score
  drawKpiCard(doc, col2X, y, 'Annual matching score', formatPercent(result.portfolio.annualScore))
  y += 35

  // Excess and unmatched
  drawKpiCard(
    doc,
    col1X,
    y,
    'Excess generation',
    `${formatNumber(Math.round(result.portfolio.totalExcessMWh))} MWh`,
  )
  drawKpiCard(
    doc,
    col2X,
    y,
    'Unmatched demand',
    `${formatNumber(Math.round(result.portfolio.totalUnmatchedMWh))} MWh`,
  )
  y += 35

  drawHr(doc, y, margin, margin + contentW)
  y += 10

  // Portfolio summary
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(14)
  setTextColour(doc, NEUTRAL_1000)
  doc.text('Portfolio summary', margin, y)
  y += 10

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  setTextColour(doc, NEUTRAL_800)

  const totalDemand = state.consumers.reduce((sum, c) => sum + c.annualMWh, 0)
  const totalGeneration = state.generators.reduce((sum, g) => sum + g.annualMWh, 0)
  doc.text(`Total demand: ${formatNumber(Math.round(totalDemand))} MWh`, margin, y)
  y += 6
  doc.text(`Total generation: ${formatNumber(Math.round(totalGeneration))} MWh`, margin, y)
  y += 6
  doc.text(`Consumers: ${state.consumers.length}  |  Generators: ${state.generators.length}`, margin, y)

  // -------------------------------------------------------------------------
  // Page 2: Inputs
  // -------------------------------------------------------------------------
  doc.addPage()
  y = 20

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  setTextColour(doc, NEUTRAL_1000)
  doc.text('Inputs', margin, y)
  y += 12

  // Consumers
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(12)
  setTextColour(doc, NEUTRAL_1000)
  doc.text('Consumers', margin, y)
  y += 8

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  setTextColour(doc, NEUTRAL_800)
  for (const consumer of state.consumers) {
    doc.text(`${consumer.name} \u2014 ${formatNumber(Math.round(consumer.annualMWh))} MWh`, margin + 4, y)
    y += 6
  }
  y += 6

  // Generators
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(12)
  setTextColour(doc, NEUTRAL_1000)
  doc.text('Generators', margin, y)
  y += 8

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  setTextColour(doc, NEUTRAL_800)
  for (const gen of state.generators) {
    doc.text(
      `${gen.name} \u2014 ${formatNumber(Math.round(gen.annualMWh))} MWh (${gen.technology})`,
      margin + 4,
      y,
    )
    y += 6
  }
  y += 6

  // Allocation matrix
  drawHr(doc, y, margin, margin + contentW)
  y += 8

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(12)
  setTextColour(doc, NEUTRAL_1000)
  doc.text('Allocation matrix (%)', margin, y)
  y += 8

  y = drawAllocationMatrix(doc, state, margin, y, contentW)

  // -------------------------------------------------------------------------
  // Page 3 (or continuation): Chart
  // -------------------------------------------------------------------------
  // If we are close to the bottom, add a new page
  if (y > 180) {
    doc.addPage()
    y = 20
  } else {
    y += 10
    drawHr(doc, y, margin, margin + contentW)
    y += 8
  }

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(14)
  setTextColour(doc, NEUTRAL_1000)
  doc.text('Monthly breakdown', margin, y)
  y += 6

  const chart = drawMonthlyBarChart(
    result.portfolio.monthlyMatchedMWh,
    result.portfolio.monthlyExcessMWh,
    result.portfolio.monthlyUnmatchedMWh,
  )
  const chartImgData = chart.toDataURL('image/png')
  // Chart: 170mm wide, aspect ratio preserved (800:400 = 2:1 so height = 85mm)
  const chartImgW = contentW
  const chartImgH = chartImgW * (400 / 800)
  doc.addImage(chartImgData, 'PNG', margin, y, chartImgW, chartImgH)

  // -------------------------------------------------------------------------
  // Footers on every page
  // -------------------------------------------------------------------------
  addFooters(doc, 'portrait')

  doc.save(`${sanitiseFilename(name)}-report.pdf`)
}

