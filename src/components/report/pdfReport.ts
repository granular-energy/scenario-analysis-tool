/**
 * Aggregate per-consumer generator contributions into portfolio-level totals.
 * Mirrors the aggregation logic in ResultsTab, extracted here for the PDF.
 */
function aggregatePortfolioGenerators(result: EngineResult): ReadonlyArray<{
  generatorId: string
  monthlyAllocatedMWh: readonly number[]
  monthlyMatchedMWh: readonly number[]
}> {
  const genMap = new Map<string, { monthlyAllocatedMWh: number[]; monthlyMatchedMWh: number[] }>()

  for (const consumer of result.consumers) {
    for (const gen of consumer.generators) {
      const existing = genMap.get(gen.generatorId)
      if (existing) {
        for (let m = 0; m < 12; m++) {
          existing.monthlyAllocatedMWh[m] += gen.monthlyAllocatedMWh[m]
          existing.monthlyMatchedMWh[m] += gen.monthlyMatchedMWh[m]
        }
      } else {
        genMap.set(gen.generatorId, {
          monthlyAllocatedMWh: [...gen.monthlyAllocatedMWh],
          monthlyMatchedMWh: [...gen.monthlyMatchedMWh],
        })
      }
    }
  }

  return Array.from(genMap.entries()).map(([generatorId, data]) => ({
    generatorId,
    ...data,
  }))
}

/**
 * Build the MonthlyBreakdownInput from an EngineResult and PortfolioState,
 * matching the same data transformation used by the on-screen chart.
 */
function buildMonthlyBreakdownInputFromResult(
  result: EngineResult,
  state: PortfolioState,
): MonthlyBreakdownInput {
  const aggregated = aggregatePortfolioGenerators(result)

  // Build lookup maps from portfolio state
  const generatorNameMap = new Map<string, string>()
  const technologyMap = new Map<string, string>()
  for (const g of state.generators) {
    generatorNameMap.set(g.uid, g.name)
    technologyMap.set(g.uid, g.technology)
  }

  return {
    monthlyScores: result.portfolio.monthlyScores,
    monthlyUnmatchedMWh: result.portfolio.monthlyUnmatchedMWh,
    generators: aggregated.map((g) => ({
      name: generatorNameMap.get(g.generatorId) ?? g.generatorId,
      technology: technologyMap.get(g.generatorId) ?? 'unknown',
      monthlyMatchedMWh: g.monthlyMatchedMWh,
      monthlyExcessMWh: g.monthlyAllocatedMWh.map((a: number, i: number) => {
        const raw = a - g.monthlyMatchedMWh[i]
        // Suppress floating-point noise -- values below 0.01 MWh are treated as zero
        return raw < 0.01 ? 0 : raw
      }),
    })),
  }
}

