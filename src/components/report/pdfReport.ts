/**
 * PDF report generation using jsPDF.
 *
 * Two entry points:
 * - generateSingleScenarioPdf: multi-page A4 portrait report for one scenario.
 * - generateComparisonPdf: A4 landscape report comparing up to 4 scenarios.
 *
 * Uses jsPDF text/drawing primitives and canvas-drawn charts added as images.
 * No html2canvas dependency -- all content is composed programmatically.
 */

import { jsPDF } from 'jspdf'
import type { PortfolioState } from '../../state/portfolioTypes'
import type { EngineResult } from '../../engine/types'
import { granularityLabel } from '../results/granularityLabel'

// ---------------------------------------------------------------------------
// Design token constants (from tokens.css, embedded here for PDF context)
// ---------------------------------------------------------------------------

const TEAL = '#00988b'
const NEUTRAL_1000 = '#2a2929'
const NEUTRAL_800 = '#56514e'
const NEUTRAL_600 = '#897f78'
const NEUTRAL_300 = '#e3e0dd'
const NEUTRAL_200 = '#f2efed'
const NEUTRAL_100 = '#fbfaf9'
const WHITE = '#ffffff'

const SERIES_COLOURS = ['#00988b', '#e9a23b', '#0f4974', '#ab80cc'] as const

const MONTH_LABELS = [
  'Jan',
  'Feb',
  'Mar',
  'Apr',
  'May',
  'Jun',
  'Jul',
  'Aug',
  'Sep',
  'Oct',
  'Nov',
  'Dec',
] as const

const FOOTER_TEXT = 'Generated by Granular Energy Scenario Analysis Tool, granular-energy.com'

// ---------------------------------------------------------------------------
// Formatting helpers
// ---------------------------------------------------------------------------

function formatNumber(n: number): string {
  return n.toLocaleString('en-GB', { maximumFractionDigits: 0 })
}

function formatPercent(n: number): string {
  return `${n.toFixed(2)} %`
}

/** Parse a hex colour string to [r, g, b] tuple (0-255). */
function hexToRgb(hex: string): [number, number, number] {
  const h = hex.replace('#', '')
  return [parseInt(h.substring(0, 2), 16), parseInt(h.substring(2, 4), 16), parseInt(h.substring(4, 6), 16)]
}

// ---------------------------------------------------------------------------
// Shared PDF helpers
// ---------------------------------------------------------------------------

/** Set text colour from a hex string. */
function setTextColour(doc: jsPDF, hex: string): void {
  const [r, g, b] = hexToRgb(hex)
  doc.setTextColor(r, g, b)
}

/** Set draw colour from a hex string. */
function setDrawColour(doc: jsPDF, hex: string): void {
  const [r, g, b] = hexToRgb(hex)
  doc.setDrawColor(r, g, b)
}

/** Set fill colour from a hex string. */
function setFillColour(doc: jsPDF, hex: string): void {
  const [r, g, b] = hexToRgb(hex)
  doc.setFillColor(r, g, b)
}

/** Add footer text to every page of the document. */
function addFooters(doc: jsPDF, orientation: 'portrait' | 'landscape'): void {
  const totalPages = doc.getNumberOfPages()
  const footerY = orientation === 'portrait' ? 290 : 203
  const centreX = orientation === 'portrait' ? 105 : 148.5
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(8)
    setTextColour(doc, NEUTRAL_600)
    doc.text(FOOTER_TEXT, centreX, footerY, { align: 'center' })
  }
}

/** Draw a horizontal rule line across the page. */
function drawHr(doc: jsPDF, y: number, x1: number, x2: number): void {
  setDrawColour(doc, NEUTRAL_300)
  doc.setLineWidth(0.3)
  doc.line(x1, y, x2, y)
}

// ---------------------------------------------------------------------------
// Canvas chart: monthly bar chart (single scenario)
// ---------------------------------------------------------------------------

function drawMonthlyBarChart(
  monthlyMatchedMWh: readonly number[],
  monthlyExcessMWh: readonly number[],
  monthlyUnmatchedMWh: readonly number[],
): HTMLCanvasElement {
  const canvas = document.createElement('canvas')
  canvas.width = 800
  canvas.height = 400
  const ctx = canvas.getContext('2d')
  if (!ctx) return canvas

  const padding = { top: 40, right: 30, bottom: 50, left: 70 }
  const chartW = canvas.width - padding.left - padding.right
  const chartH = canvas.height - padding.top - padding.bottom

  // Compute y-axis max
  const maxVal = Math.max(
    ...monthlyMatchedMWh.map((m, i) => m + (monthlyExcessMWh[i] ?? 0) + (monthlyUnmatchedMWh[i] ?? 0)),
    1,
  )
  const yMax = maxVal * 1.15

  // Background
  ctx.fillStyle = WHITE
  ctx.fillRect(0, 0, canvas.width, canvas.height)

  // Grid lines (dotted)
  const gridLines = 5
  ctx.setLineDash([2, 3])
  ctx.strokeStyle = 'rgba(0, 0, 0, 0.15)'
  ctx.lineWidth = 1
  for (let i = 0; i <= gridLines; i++) {
    const gy = padding.top + (chartH / gridLines) * i
    ctx.beginPath()
    ctx.moveTo(padding.left, gy)
    ctx.lineTo(padding.left + chartW, gy)
    ctx.stroke()
  }
  ctx.setLineDash([])

  // Y-axis labels
  ctx.fillStyle = NEUTRAL_600
  ctx.font = '12px sans-serif'
  ctx.textAlign = 'right'
  ctx.textBaseline = 'middle'
  for (let i = 0; i <= gridLines; i++) {
    const val = yMax - (yMax / gridLines) * i
    const gy = padding.top + (chartH / gridLines) * i
    ctx.fillText(formatNumber(Math.round(val)), padding.left - 8, gy)
  }

  // Y-axis title
  ctx.fillStyle = NEUTRAL_600
  ctx.font = '11px sans-serif'
  ctx.textAlign = 'left'
  ctx.fillText('MWh', padding.left - 8, padding.top - 20)

  const barW = chartW / 12
  const barPad = barW * 0.15

  for (let m = 0; m < 12; m++) {
    const x = padding.left + m * barW + barPad
    const w = barW - 2 * barPad

    const matched = monthlyMatchedMWh[m] ?? 0
    const excess = monthlyExcessMWh[m] ?? 0
    const unmatched = monthlyUnmatchedMWh[m] ?? 0

    // Matched (teal)
    const matchedH = (matched / yMax) * chartH
    const matchedY = padding.top + chartH - matchedH
    ctx.fillStyle = TEAL
    ctx.fillRect(x, matchedY, w, matchedH)

    // Unmatched (light grey, hatched appearance via lighter fill)
    const unmatchedH = (unmatched / yMax) * chartH
    const unmatchedY = matchedY - unmatchedH
    ctx.fillStyle = NEUTRAL_300
    ctx.fillRect(x, unmatchedY, w, unmatchedH)

    // Excess (lighter teal above matched)
    const excessH = (excess / yMax) * chartH
    const excessY = matchedY - excessH
    ctx.fillStyle = '#94d1cc' // teal-500
    ctx.fillRect(x, excessY, w, excessH)

    // X-axis label
    ctx.fillStyle = NEUTRAL_600
    ctx.font = '12px sans-serif'
    ctx.textAlign = 'center'
    ctx.textBaseline = 'top'
    ctx.fillText(MONTH_LABELS[m], x + w / 2, padding.top + chartH + 8)
  }

  // Chart title
  ctx.fillStyle = NEUTRAL_1000
  ctx.font = 'bold 14px sans-serif'
  ctx.textAlign = 'left'
  ctx.textBaseline = 'top'
  ctx.fillText('Monthly breakdown', padding.left, 8)

  // Legend
  const legendY = padding.top + chartH + 30
  const legendItems: Array<{ label: string; colour: string }> = [
    { label: 'Matched', colour: TEAL },
    { label: 'Unmatched demand', colour: NEUTRAL_300 },
    { label: 'Excess', colour: '#94d1cc' },
  ]
  let lx = padding.left
  ctx.font = '11px sans-serif'
  ctx.textBaseline = 'middle'
  for (const item of legendItems) {
    ctx.fillStyle = item.colour
    ctx.fillRect(lx, legendY - 5, 12, 12)
    ctx.fillStyle = NEUTRAL_800
    ctx.textAlign = 'left'
    ctx.fillText(item.label, lx + 16, legendY + 1)
    lx += ctx.measureText(item.label).width + 36
  }

  return canvas
}

// ---------------------------------------------------------------------------
// Canvas chart: monthly score line chart (comparison)
// ---------------------------------------------------------------------------

function drawMonthlyScoreLineChart(
  scenarios: readonly { readonly name: string; readonly monthlyScores: readonly number[] }[],
): HTMLCanvasElement {
  const canvas = document.createElement('canvas')
  canvas.width = 800
  canvas.height = 350
  const ctx = canvas.getContext('2d')
  if (!ctx) return canvas

  const padding = { top: 40, right: 30, bottom: 60, left: 60 }
  const chartW = canvas.width - padding.left - padding.right
  const chartH = canvas.height - padding.top - padding.bottom

  // Background
  ctx.fillStyle = WHITE
  ctx.fillRect(0, 0, canvas.width, canvas.height)

  // Y-axis range: 0 to max(all scores) * 1.1 (clamped to at least 100)
  const allScores = scenarios.flatMap((s) => [...s.monthlyScores])
  const yMax = Math.max(Math.max(...allScores) * 1.1, 100)

  // Grid lines (dotted)
  const gridLines = 5
  ctx.setLineDash([2, 3])
  ctx.strokeStyle = 'rgba(0, 0, 0, 0.15)'
  ctx.lineWidth = 1
  for (let i = 0; i <= gridLines; i++) {
    const gy = padding.top + (chartH / gridLines) * i
    ctx.beginPath()
    ctx.moveTo(padding.left, gy)
    ctx.lineTo(padding.left + chartW, gy)
    ctx.stroke()
  }
  ctx.setLineDash([])

  // Y-axis labels
  ctx.fillStyle = NEUTRAL_600
  ctx.font = '12px sans-serif'
  ctx.textAlign = 'right'
  ctx.textBaseline = 'middle'
  for (let i = 0; i <= gridLines; i++) {
    const val = yMax - (yMax / gridLines) * i
    const gy = padding.top + (chartH / gridLines) * i
    ctx.fillText(`${val.toFixed(0)}%`, padding.left - 8, gy)
  }

  // Y-axis title
  ctx.fillStyle = NEUTRAL_600
  ctx.font = '11px sans-serif'
  ctx.textAlign = 'left'
  ctx.fillText('Hourly score (%)', padding.left - 8, padding.top - 20)

  // X-axis labels
  ctx.fillStyle = NEUTRAL_600
  ctx.font = '12px sans-serif'
  ctx.textAlign = 'center'
  ctx.textBaseline = 'top'
  for (let m = 0; m < 12; m++) {
    const x = padding.left + (m / 11) * chartW
    ctx.fillText(MONTH_LABELS[m], x, padding.top + chartH + 8)
  }

  // Draw lines for each scenario
  for (let si = 0; si < scenarios.length; si++) {
    const scores = scenarios[si].monthlyScores
    const colour = SERIES_COLOURS[si % SERIES_COLOURS.length]
    ctx.strokeStyle = colour
    ctx.lineWidth = 2.5
    ctx.lineJoin = 'round'
    ctx.lineCap = 'round'
    ctx.beginPath()
    for (let m = 0; m < 12; m++) {
      const x = padding.left + (m / 11) * chartW
      const y = padding.top + chartH - ((scores[m] ?? 0) / yMax) * chartH
      if (m === 0) {
        ctx.moveTo(x, y)
      } else {
        ctx.lineTo(x, y)
      }
    }
    ctx.stroke()

    // Draw markers
    ctx.fillStyle = colour
    for (let m = 0; m < 12; m++) {
      const x = padding.left + (m / 11) * chartW
      const y = padding.top + chartH - ((scores[m] ?? 0) / yMax) * chartH
      ctx.beginPath()
      ctx.arc(x, y, 3, 0, Math.PI * 2)
      ctx.fill()
    }
  }

  // Chart title
  ctx.fillStyle = NEUTRAL_1000
  ctx.font = 'bold 14px sans-serif'
  ctx.textAlign = 'left'
  ctx.textBaseline = 'top'
  ctx.fillText('Monthly hourly scores', padding.left, 8)

  // Legend
  const legendY = padding.top + chartH + 32
  let lx = padding.left
  ctx.font = '11px sans-serif'
  ctx.textBaseline = 'middle'
  for (let si = 0; si < scenarios.length; si++) {
    const colour = SERIES_COLOURS[si % SERIES_COLOURS.length]
    // Line swatch
    ctx.strokeStyle = colour
    ctx.lineWidth = 2.5
    ctx.beginPath()
    ctx.moveTo(lx, legendY)
    ctx.lineTo(lx + 20, legendY)
    ctx.stroke()
    // Label
    ctx.fillStyle = NEUTRAL_800
    ctx.textAlign = 'left'
    ctx.fillText(scenarios[si].name, lx + 24, legendY)
    lx += ctx.measureText(scenarios[si].name).width + 48
  }

  return canvas
}

