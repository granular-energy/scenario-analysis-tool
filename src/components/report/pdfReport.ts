/** Draw a small KPI card (label + value) at a given position. */
function drawKpiCard(doc: jsPDF, x: number, y: number, label: string, value: string): void {
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  setTextColour(doc, NEUTRAL_600)
  doc.text(label, x, y)

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  setTextColour(doc, NEUTRAL_1000)
  doc.text(value, x, y + 8)
}

/** Draw the allocation matrix table. Returns the y position after the table. */
function drawAllocationMatrix(
  doc: jsPDF,
  state: PortfolioState,
  x: number,
  startY: number,
  contentW: number,
): number {
  const { consumers, generators, matrix, allocationMode, consumptionMatrix } = state
  const activeMatrix = allocationMode === 'consumption-share' ? consumptionMatrix : matrix
  if (consumers.length === 0 || generators.length === 0) return startY

  // Column layout: first column for generator name, then one per consumer
  const cols = consumers.length + 1
  const colW = contentW / cols
  const rowH = 7
  let y = startY

  // Header row
  setFillColour(doc, NEUTRAL_200)
  doc.rect(x, y - 4, contentW, rowH, 'F')

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(8)
  setTextColour(doc, NEUTRAL_1000)
  doc.text('Generator', x + 2, y)
  for (let ci = 0; ci < consumers.length; ci++) {
    const cx = x + (ci + 1) * colW
    // Truncate long names
    const displayName =
      consumers[ci].name.length > 18 ? consumers[ci].name.substring(0, 17) + '\u2026' : consumers[ci].name
    doc.text(displayName, cx + 2, y)
  }
  y += rowH

  drawHr(doc, y - 2, x, x + contentW)

  // Data rows
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8)
  for (let gi = 0; gi < generators.length; gi++) {
    const gen = generators[gi]

    // Alternate row background
    if (gi % 2 === 1) {
      setFillColour(doc, NEUTRAL_100)
      doc.rect(x, y - 4, contentW, rowH, 'F')
    }

    setTextColour(doc, NEUTRAL_800)
    const genName = gen.name.length > 18 ? gen.name.substring(0, 17) + '\u2026' : gen.name
    doc.text(genName, x + 2, y)

    for (let ci = 0; ci < consumers.length; ci++) {
      const pct = activeMatrix[gen.uid]?.[consumers[ci].uid] ?? 0
      const cx = x + (ci + 1) * colW
      setTextColour(doc, pct > 0 ? NEUTRAL_1000 : NEUTRAL_600)
      doc.text(`${pct.toFixed(0)}%`, cx + 2, y)
    }
    y += rowH
  }

  return y
}

/** Draw the assumptions table for the comparison PDF. Returns y after table. */
function drawComparisonAssumptionsTable(
  doc: jsPDF,
  scenarios: readonly ComparisonScenario[],
  x: number,
  startY: number,
  contentW: number,
): number {
  const cols = scenarios.length + 1
  const colW = contentW / cols
  const rowH = 7
  let y = startY

  // Header row
  setFillColour(doc, NEUTRAL_200)
  doc.rect(x, y - 4, contentW, rowH, 'F')

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(8)
  setTextColour(doc, NEUTRAL_1000)
  doc.text('', x + 2, y) // empty first cell
  for (let i = 0; i < scenarios.length; i++) {
    const sx = x + (i + 1) * colW
    doc.text(scenarios[i].name, sx + 2, y)
  }
  y += rowH
  drawHr(doc, y - 2, x, x + contentW)

  // Row: Allocation mode
  y = drawAssumptionRow(
    doc,
    'Allocation mode',
    scenarios.map((s) =>
      s.portfolio.allocationMode === 'consumption-share'
        ? 'Set % of consumption'
        : 'Share of generator output',
    ),
    x,
    y,
    colW,
  )

  // Row: Allocation method
  y = drawAssumptionRow(
    doc,
    'Allocation method',
    scenarios.map((s) => granularityLabel(s.portfolio.granularity)),
    x,
    y,
    colW,
  )

  // Row: Consumers
  y = drawAssumptionRow(
    doc,
    'Consumers',
    scenarios.map((s) => s.portfolio.consumers.map((c) => c.name).join(', ')),
    x,
    y,
    colW,
  )

  // Row: Generators
  y = drawAssumptionRow(
    doc,
    'Generators',
    scenarios.map((s) => s.portfolio.generators.map((g) => g.name).join(', ')),
    x,
    y,
    colW,
  )

  return y
}

/** Draw one row of the assumptions table. Returns y after row. */
function drawAssumptionRow(
  doc: jsPDF,
  label: string,
  values: string[],
  x: number,
  y: number,
  colW: number,
): number {
  const rowH = 7

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(8)
  setTextColour(doc, NEUTRAL_600)
  doc.text(label, x + 2, y)

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8)
  setTextColour(doc, NEUTRAL_800)

  // Check if values differ across scenarios
  const allSame = values.every((v) => v === values[0])

  for (let i = 0; i < values.length; i++) {
    const sx = x + (i + 1) * colW
    // Highlight differing cells
    if (!allSame) {
      setFillColour(doc, '#fff8eb') // warning-bg for differences
      doc.rect(sx, y - 4, colW, rowH, 'F')
    }
    setTextColour(doc, NEUTRAL_800)
    // Truncate long text
    const maxChars = Math.floor(colW / 2)
    const displayVal =
      values[i].length > maxChars ? values[i].substring(0, maxChars - 1) + '\u2026' : values[i]
    doc.text(displayVal, sx + 2, y)
  }

  return y + rowH
}

/** Sanitise a string for use as a filename. */
function sanitiseFilename(name: string): string {
  return name
    .replace(/[^a-zA-Z0-9\s-]/g, '')
    .replace(/\s+/g, '-')
    .toLowerCase()
    .substring(0, 60)
}
