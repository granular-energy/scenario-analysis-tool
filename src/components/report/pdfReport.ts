export async function generateComparisonPdf(scenarios: readonly ComparisonScenario[]): Promise<void> {
  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' })
  // A4 landscape: 297 x 210 mm
  const pageW = 297
  const pageH = 210
  const margin = 15
  const contentW = pageW - 2 * margin

  // -------------------------------------------------------------------------
  // Page 1: Tile columns + Chart
  // -------------------------------------------------------------------------

  // Header band
  setFillColour(doc, '#e6f5f3')
  doc.rect(0, 0, pageW, 30, 'F')

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(18)
  setTextColour(doc, NEUTRAL_1000)
  doc.text('Scenario comparison', margin, 20)

  let y = 38

  // Tile columns
  const colCount = scenarios.length
  const colW = contentW / colCount
  const tileH = 60

  for (let i = 0; i < colCount; i++) {
    const sc = scenarios[i]
    const cx = margin + i * colW
    const tilePad = 4

    // Card background
    setFillColour(doc, WHITE)
    setDrawColour(doc, NEUTRAL_300)
    doc.setLineWidth(0.3)
    doc.roundedRect(cx + tilePad, y, colW - 2 * tilePad, tileH, 2, 2, 'FD')

    // Scenario name with colour indicator
    const seriesColour = SERIES_COLOURS[i % SERIES_COLOURS.length]
    setFillColour(doc, seriesColour)
    doc.circle(cx + tilePad + 6, y + 10, 2.5, 'F')

    doc.setFont('helvetica', 'bold')
    doc.setFontSize(11)
    setTextColour(doc, NEUTRAL_1000)
    doc.text(sc.name, cx + tilePad + 12, y + 11)

    // Scores
    let ty = y + 20
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(9)
    setTextColour(doc, NEUTRAL_600)
    doc.text('Hourly score', cx + tilePad + 6, ty)
    doc.setFont('helvetica', 'bold')
    setTextColour(doc, NEUTRAL_1000)
    doc.text(formatPercent(sc.results.hourlyScore), cx + tilePad + 6, ty + 5)

    ty += 12
    doc.setFont('helvetica', 'normal')
    setTextColour(doc, NEUTRAL_600)
    doc.text('Annual score', cx + tilePad + 6, ty)
    doc.setFont('helvetica', 'bold')
    setTextColour(doc, NEUTRAL_1000)
    doc.text(formatPercent(sc.results.annualScore), cx + tilePad + 6, ty + 5)

    // Excess / unmatched in second column of the tile
    const halfCol = (colW - 2 * tilePad) / 2
    ty = y + 20
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(9)
    setTextColour(doc, NEUTRAL_600)
    doc.text('Excess MWh', cx + tilePad + halfCol, ty)
    doc.setFont('helvetica', 'bold')
    setTextColour(doc, NEUTRAL_1000)
    doc.text(formatNumber(Math.round(sc.results.totalExcessMWh)), cx + tilePad + halfCol, ty + 5)

    ty += 12
    doc.setFont('helvetica', 'normal')
    setTextColour(doc, NEUTRAL_600)
    doc.text('Unmatched MWh', cx + tilePad + halfCol, ty)
    doc.setFont('helvetica', 'bold')
    setTextColour(doc, NEUTRAL_1000)
    doc.text(formatNumber(Math.round(sc.results.totalUnmatchedMWh)), cx + tilePad + halfCol, ty + 5)
  }

  y += tileH + 8

  // Monthly score line chart
  const lineChart = drawMonthlyScoreLineChart(
    scenarios.map((s) => ({ name: s.name, monthlyScores: s.results.monthlyScores })),
  )
  const lineChartImg = lineChart.toDataURL('image/png')
  const lineChartW = contentW
  const lineChartH = lineChartW * (350 / 800)
  // If chart doesn't fit on current page, add new page
  if (y + lineChartH > pageH - 25) {
    doc.addPage()
    y = 20
  }
  doc.addImage(lineChartImg, 'PNG', margin, y, lineChartW, lineChartH)
  y += lineChartH + 8

  // -------------------------------------------------------------------------
  // Assumptions table (may overflow to page 2)
  // -------------------------------------------------------------------------
  if (y > pageH - 60) {
    doc.addPage()
    y = 20
  }

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(13)
  setTextColour(doc, NEUTRAL_1000)
  doc.text('Assumptions', margin, y)
  y += 8

  y = drawComparisonAssumptionsTable(doc, scenarios, margin, y, contentW)

  // -------------------------------------------------------------------------
  // Footers on every page
  // -------------------------------------------------------------------------
  addFooters(doc, 'landscape')

  doc.save('scenario-comparison.pdf')
}

